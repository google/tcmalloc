// Columns in the following tables:
// - bytes: size of the size class
// - span_bytes: number of bytes per span
// - batch: preferred number of objects for transfers between caches
// - class: size class number
// - objs: number of objects per span
// - waste/fixed: fixed per-size-class overhead due to end-of-span fragmentation
//   and other factors. For instance, if we have a 96 byte size class, and use
//   a single 8KiB page, then we will hold 85 objects per span, and have 32
//   bytes left over. There is also a fixed component of 64 bytes of TCMalloc
//   metadata per span. Together, the fixed overhead would be wasted/allocated
//   = (32 + 64) / (8192 - 32) ~= 1.2%.
// - waste/sampling: overhead due to heap sampling
//   (rounding to page size, metadata).
// - waste/int.frag: overhead due to internal fragmentation (allocations that
//   were smaller than the size class). Does not take into account the rounding
//   to 8 or 16 bytes required for alignment.
// - inc: increment from the previous size class. This caps the internal
//   fragmentation overhead component based on mismatches between the number
//   of bytes requested and the number of bytes provided by the size class.
//   Together they sum to the total overhead; for instance if you asked for
//   a 50-byte allocation that rounds up to a 64-byte size class, the internal
//   fragmentation would be (64-50)/50 = 28%, and if waste were 22% it would
//   mean (on average) 25 bytes of overhead for allocations of that size.
// - used: average number of gigabytes used, per process, by allocations
//   landing in this size class.

